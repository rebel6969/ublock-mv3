// Assemble the loadable extension: bundle the service worker, copy runtime
// source, build the manifest from the emitted rulesets, and enforce the two
// invariants that otherwise fail silently.
import {
    readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync, readdirSync, statSync,
} from 'node:fs';
import { resolve } from 'node:path';
import { build } from 'esbuild';
import { ROOT, PARENT, readBackup, describeConfig } from './lib/backup.mjs';
import { ENV } from './lib/env.mjs';
import { SHARD_COUNT, shardOf } from './lib/shardcfg.mjs';

const SRC = resolve(ROOT, 'src');
const DIST = resolve(ROOT, 'extension');
const BUILD = resolve(ROOT, 'build');
const UBO = resolve(PARENT, 'uBlock0.chromium');

/* ---------------------------------------------------------------------- */
/* Invariant 1: the runtime env must match the build env                   */

function syncEnvRuntime() {
    const target = resolve(SRC, 'lib', 'env-runtime.js');
    const generated = `// GENERATED by tools/assemble.mjs from tools/lib/env.mjs -- do not edit.
//
// The filter-list preprocessor environment, shared by the build and the service
// worker. If these drift, a list refetched by "Update all" compiles differently
// from how it was compiled at build time, and filters appear or vanish with no
// error anywhere. See tools/lib/env.mjs for why each token is present.
export const ENV = ${JSON.stringify(ENV, null, 4)};
`;
    const previous = existsSync(target) ? readFileSync(target, 'utf-8') : '';
    writeFileSync(target, generated);
    return previous !== generated;
}

/* ---------------------------------------------------------------------- */
/* Invariant 2: build and runtime must shard hostnames identically         */

async function verifyShardAgreement() {
    const mod = await import(`file://${resolve(SRC, 'lib', 'shard.js')}`);
    if ( mod.SHARD_COUNT !== SHARD_COUNT ) {
        throw new Error(
            `shard count mismatch: src/lib/shard.js has ${mod.SHARD_COUNT}, ` +
            `tools/lib/shardcfg.mjs has ${SHARD_COUNT}`
        );
    }
    // Compare across a broad sample rather than a token few.
    const samples = [];
    for ( let i = 0; i < 20000; i++ ) {
        samples.push(`h${i}.example${i % 97}.co${i % 7}.uk`);
    }
    samples.push('youtube.com', 'www.youtube.com', 'a.b.c.d.example.com', 'xn--80ak6aa92e.com');
    for ( const h of samples ) {
        if ( mod.shardOf(h) !== shardOf(h) ) {
            throw new Error(`shardOf disagreement on "${h}": ` +
                `runtime=${mod.shardOf(h)} build=${shardOf(h)}`);
        }
    }
    return samples.length;
}

